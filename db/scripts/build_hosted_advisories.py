"""Render the audited legacy-Supabase bridge; never connects to a database.

Run with the database environment: .local/database-venv/bin/python
db/scripts/build_hosted_advisories.py. Do not stamp the local Alembic chain.
"""
from pathlib import Path
import runpy
from types import SimpleNamespace

ROOT = Path(__file__).resolve().parents[2]


def migration_sql(filename):
    module = runpy.run_path(str(ROOT / 'db/migrations/versions' / filename))
    statements = []
    upgrade = module['upgrade']
    upgrade.__globals__['op'] = SimpleNamespace(execute=statements.append)
    upgrade()
    return '\n'.join(s.strip().rstrip(';') + ';' for s in statements)


def render():
    # Reuse reviewed table/view definitions rather than maintaining two schemas.
    history = migration_sql('0003_publication_history.py')
    history = history[history.index('CREATE TABLE public.pipeline_runs'):history.index('CREATE INDEX pipeline_runs_started_at_idx')].strip()
    return '\n\n'.join([
        '-- Generated by db/scripts/build_hosted_advisories.py; review before running.\n'
        '-- Target: audited six-table Supabase legacy schema. NOT an Alembic baseline.\n'
        '-- New credentials are configured separately; roles start NOLOGIN.\n'
        'BEGIN;\nSET LOCAL lock_timeout = \'5s\';\nSET LOCAL statement_timeout = \'60s\';',
        """DO $$ BEGIN
            IF current_user <> 'postgres' THEN
                RAISE EXCEPTION 'Run as the audited postgres database owner';
            END IF;
            IF EXISTS (SELECT FROM pg_roles WHERE rolname IN
                ('safetrip_reader','safetrip_writer','safetrip_migrator'))
                OR EXISTS (SELECT FROM pg_namespace WHERE nspname='advisory')
                OR to_regclass('public.pipeline_runs') IS NOT NULL
                OR to_regclass('public.raw_feeds') IS NOT NULL
                OR to_regclass('public.advisory_summaries') IS NOT NULL
                OR to_regclass('public.alembic_version') IS NOT NULL THEN
                RAISE EXCEPTION 'Unexpected existing foundation; stop and re-audit, do not rerun';
            END IF;
            IF (SELECT count(*) FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
                WHERE n.nspname='public' AND c.relname IN
                ('countries','culture','scores','bert_scores','clustering','travel_advisories')
                AND c.relkind='r' AND c.relrowsecurity) <> 6 THEN
                RAISE EXCEPTION 'Expected six existing application tables with RLS';
            END IF;
        END $$;
        CREATE ROLE safetrip_reader NOLOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
        CREATE ROLE safetrip_writer NOLOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
        GRANT USAGE ON SCHEMA public TO safetrip_reader, safetrip_writer;
        DO $$ BEGIN
            EXECUTE format('GRANT CONNECT ON DATABASE %I TO safetrip_reader, safetrip_writer', current_database());
        END $$;
        GRANT SELECT ON public.countries TO safetrip_writer;
        CREATE POLICY advisory_writer_country_read ON public.countries
            FOR SELECT TO safetrip_writer USING (true);
        GRANT SELECT ON public.countries, public.culture, public.scores TO safetrip_reader;
        CREATE POLICY advisory_reader_countries ON public.countries FOR SELECT TO safetrip_reader USING (true);
        CREATE POLICY advisory_reader_culture ON public.culture FOR SELECT TO safetrip_reader USING (true);
        CREATE POLICY advisory_reader_scores ON public.scores FOR SELECT TO safetrip_reader USING (true);
        -- XKX is the application's Kosovo join key, also used by the source adapters.
        INSERT INTO public.countries(iso3,name,iso2,continent)
            VALUES ('XKX','Kosovo','XK','Europe') ON CONFLICT (iso3) DO NOTHING;""",
        history,
        """CREATE INDEX pipeline_runs_started_at_idx ON public.pipeline_runs(started_at DESC);
        ALTER TABLE public.pipeline_runs ENABLE ROW LEVEL SECURITY;
        GRANT SELECT,INSERT,UPDATE ON public.pipeline_runs TO safetrip_writer;
        CREATE POLICY worker_runs ON public.pipeline_runs TO safetrip_writer USING (true) WITH CHECK (true);""",
        migration_sql('0004_raw_feeds.py'),
        migration_sql('0006_multisource_advisories.py'),
        migration_sql('0007_advisory_display.py'),
        """-- Supabase may give API roles default privileges on newly created public objects.
        REVOKE ALL ON public.pipeline_runs, public.raw_feeds, public.advisory_summaries
            FROM PUBLIC, anon, authenticated, service_role;
        REVOKE ALL ON SCHEMA advisory FROM PUBLIC, anon, authenticated, service_role, safetrip_reader;
        REVOKE ALL ON ALL TABLES IN SCHEMA advisory FROM PUBLIC, anon, authenticated, service_role;
        -- Fail closed if inherited or default grants undermine this installation.
        DO $$ DECLARE r text; t text; p text; BEGIN
            FOREACH r IN ARRAY ARRAY['anon','authenticated','service_role'] LOOP
                FOREACH t IN ARRAY ARRAY['public.pipeline_runs','public.raw_feeds','public.advisory_summaries'] LOOP
                    FOREACH p IN ARRAY ARRAY['SELECT','INSERT','UPDATE','DELETE','TRUNCATE','REFERENCES','TRIGGER'] LOOP
                        IF has_table_privilege(r,t,p) THEN
                            RAISE EXCEPTION 'Unexpected API access to new relation: % % %', r,t,p;
                        END IF;
                    END LOOP;
                END LOOP;
                IF has_schema_privilege(r,'advisory','USAGE') OR has_schema_privilege(r,'advisory','CREATE') THEN
                    RAISE EXCEPTION 'Unexpected API access to private schema: %', r;
                END IF;
            END LOOP;
            FOREACH r IN ARRAY ARRAY['safetrip_reader','safetrip_writer'] LOOP
                IF has_schema_privilege(r,'public','CREATE') THEN
                    RAISE EXCEPTION 'Application role can create public objects: %', r;
                END IF;
                FOREACH t IN ARRAY ARRAY['public.scores','public.clustering','public.bert_scores','public.travel_advisories','public.countries','public.culture'] LOOP
                    FOREACH p IN ARRAY ARRAY['INSERT','UPDATE','DELETE','TRUNCATE'] LOOP
                        IF has_table_privilege(r,t,p) THEN
                            RAISE EXCEPTION 'Application role has unexpected legacy write access: % %',r,t;
                        END IF;
                    END LOOP;
                END LOOP;
            END LOOP;
        END $$;
        COMMIT;""",
    ]) + '\n'


if __name__ == '__main__':
    path = ROOT / 'db/hosted/001_advisory_foundation.sql'
    path.write_text(render())
    print('Rendered', path.relative_to(ROOT), '(no database connection).')
